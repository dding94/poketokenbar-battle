import {build} from 'esbuild';
import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {options} from './options.mjs';
await build({...options(),entryPoints:['src/index.js'],outfile:'dist/battle-engine.js'});
const bytes = await readFile('dist/battle-engine.js');
const hash = createHash('sha256').update(bytes).digest('hex');
await writeFile('dist/battle-engine.sha256', `${createHash('sha256').update(bytes).digest('hex')}  battle-engine.js\n`);
await writeFile('../Sources/PokeTokenBar/Core/BattleEngineManifest.swift',
  `// Generated by engine/scripts/build.mjs. Commit with the engine bundle.\nenum BattleEngineManifest {\n    static let sha256 = "${hash}"\n}\n`);
